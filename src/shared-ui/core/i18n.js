export const SUPPORTED_LOCALES = Object.keys(MESSAGES);

// Per-locale key lists, so a test can catch a string that only exists in English
// (`t()` would hide it behind the English fallback).
export const MESSAGE_KEYS = Object.fromEntries(
  SUPPORTED_LOCALES.map((locale) => [locale, Object.keys(MESSAGES[locale])])
);

/**
 * `preferredLanguages` lets a host without `navigator` — the Electron main
 * process, which localizes the native menu and tray — pass its OS locale list.
 * Without it `auto` would resolve to English there even on a Chinese system.
 */
export function resolveLocale(preference = 'auto', preferredLanguages = null) {
  if (preference && preference !== 'auto' && MESSAGES[preference]) return preference;
  const langs = preferredLanguages
    ? (Array.isArray(preferredLanguages) ? preferredLanguages : [preferredLanguages])
    : (typeof navigator !== 'undefined' ? (navigator.languages || [navigator.language]) : ['en']);
  for (const lang of langs) {
    const lower = String(lang || '').toLowerCase();
    // Region decides the script before the language does: `zh-HK`/`zh-MO` are
    // Traditional in practice, and normalizeLanguageSetting() in the desktop main
    // process maps them the same way, so the two must not diverge.
    if (/^zh-(tw|hk|mo)\b/.test(lower) || lower.startsWith('zh-hant')) return 'zh-TW';
    if (lower.startsWith('zh')) return 'zh-CN';
    if (lower.startsWith('ja')) return 'ja';
    if (lower.startsWith('ko')) return 'ko';
    if (lower.startsWith('en')) return 'en';
  }
  return 'en';
}

export function t(locale, key, params = {}) {
  const table = MESSAGES[locale] || MESSAGES.en;
  let text = table[key] || MESSAGES.en[key] || key;
  for (const [name, value] of Object.entries(params)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function applyI18n(root, locale) {
  for (const el of root.querySelectorAll('[data-i18n]')) {
    el.textContent = t(locale, el.getAttribute('data-i18n'));
  }
}
